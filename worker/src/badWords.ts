// 공개 코스 이름 거르기 (모두의 코스, 애플 심사 1.2 "불쾌한 콘텐츠 거르기"): 이름에서 띄어쓰기·기호를 뺀 뒤 이 말이 들어 있으면 받지 않는다.
// 앱은 서버가 준 문구만 보인다 (목록을 두 곳에 두지 않게). 더할 땐 여기만 고친다.
// 땅 이름에 들어가는 말(대마도·토토로 같은)은 넣지 않는다 — 멀쩡한 코스 이름이 막히지 않게
export const BAD_WORDS: readonly string[] = [
  '씨발', '시발', 'ㅅㅂ', '씨빨', '시바ㄹ', '병신', 'ㅂㅅ', '븅신', '좆', '존나', 'ㅈㄴ', '개새끼', '개새', '새끼', '미친놈', '미친년', '지랄', 'ㅈㄹ',
  '닥쳐', '꺼져', '엠창', '느금', '니애미', '창녀', '걸레', '보지', '자지', '섹스', '야동', '강간',
  '살인', '자살', '마약', '필로폰', '도박', '카지노', '한남', '김치녀', '틀딱', '장애인새끼', '쪽바리', '짱깨', '흑형',
  'fuck', 'shit', 'bitch', 'porn', 'nigger', 'nigga', 'cunt',
];

/** 이름에 쓸 수 없는 말이 있는지 */
export function hasBadWord(name: string): boolean {
  const s = name.toLowerCase().replace(/[\s\p{P}\p{S}0-9_]+/gu, '');
  return BAD_WORDS.some((w) => s.includes(w));
}
