// 모두의 코스 지역 (설계 2부, 시안 ⑦ "경기·강원"): 시·도 17개. 공개할 때 출발점으로 짐작해 골라 두고 사용자가 바꿀 수 있다.
// 서버에 위치를 보내 주소를 묻지 않는다(길찾기 회사 API 를 더 쓰지 않게) — 대표 지점 중 가장 가까운 곳이라 경계 근처는 틀릴 수 있다
export const SIDOS = ['서울', '부산', '대구', '인천', '광주', '대전', '울산', '세종', '경기', '강원', '충북', '충남', '전북', '전남', '경북', '경남', '제주'] as const;
export type Sido = (typeof SIDOS)[number];

/** 시·도 대표 지점 (넓은 도는 가운데쯤) */
const POINTS: Record<Sido, [number, number]> = {
  서울: [37.5665, 126.978],
  부산: [35.1796, 129.0756],
  대구: [35.8714, 128.6014],
  인천: [37.4563, 126.7052],
  광주: [35.1595, 126.8526],
  대전: [36.3504, 127.3845],
  울산: [35.5384, 129.3114],
  세종: [36.48, 127.289],
  경기: [37.41, 127.25],
  강원: [37.75, 128.3],
  충북: [36.8, 127.7],
  충남: [36.5, 126.8],
  전북: [35.72, 127.15],
  전남: [34.86, 126.99],
  경북: [36.4, 128.9],
  경남: [35.3, 128.25],
  제주: [33.4, 126.55],
};

export function guessSido(lat: number, lon: number): Sido {
  let best: Sido = '서울';
  let bestD = Infinity;
  for (const s of SIDOS) {
    const [la, lo] = POINTS[s];
    const d = ((lat - la) * 111) ** 2 + ((lon - lo) * 88) ** 2;
    if (d < bestD) {
      bestD = d;
      best = s;
    }
  }
  return best;
}
